def fmt_candidate(c):
    lines = ["        {"]
    items = list(c.items())
    for i, (k, v) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f"          {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}{comma}")
    lines.append("        }")
    return "\n".join(lines)


def main():
    write = "--write" in sys.argv
    by_set = {}
    for rep in REPLACEMENTS:
        by_set.setdefault(rep[0][2:4], []).append(rep)
    for nn, reps in sorted(by_set.items()):
        path = ROOT / "data" / f"set-{nn}.json"
        text = path.read_bytes().decode("utf-8")
        for wid, example, answer, translation, source in reps:
            assert example.count(answer) == 1, (wid, "空欄の語句が本文にちょうど1回出ること", example.count(answer))
            cloze = example.replace(answer, "（　）", 1)
            start = text.index(f'"id": "{wid}"')
            nxt = text.find('"id": "kv', start + 1)
            end = nxt if nxt != -1 else len(text)
            block = text[start:end]
            assert '"exampleForm": "prose"' in block, wid
            head, sep, tail = block.partition('"examples": [')
            for key, value in (("example", example), ("translation", translation), ("source", source), ("cloze", cloze)):
                pattern = re.compile(rf'("{key}": )"(?:[^"\\]|\\.)*"')
                assert len(pattern.findall(head)) == 1, (wid, key)
                head = pattern.sub(lambda m: m.group(1) + json.dumps(value, ensure_ascii=False), head, count=1)
            if sep:
                close = tail.index("\n      ]")
                cand = {"sourceType": "prose", "example": example, "translation": translation,
                        "source": source, "cloze": cloze, "exampleForm": "prose"}
                tail = "\n" + fmt_candidate(cand) + tail[close:]
            new = head + sep + tail
            text = text[:start] + new + text[end:]
            print(f"{wid}{' (+examples)' if sep else ''}: {example}")
        json.loads(text)
        if write:
            path.write_bytes(text.encode("utf-8"))
    print("written" if write else "dry run (--write で書き込む)")


if __name__ == "__main__":
    main()
